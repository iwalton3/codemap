/**
 * The standard's in-force rules rendered as `docs/rules/` markdown, in the format Acme's
 * hand-written rules use (plan 2026-10-07-ladder-support, phase B).
 *
 * It is a PROJECTION and never a second authority: every file says so in its first line,
 * a write replaces every file it generated, and it never writes over a `docs/rules/` git
 * tracks — a repository keeps its committed rules until it is cut over (B2).
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import type { Anchor, Operation, Pointer, Requirement } from "./schema.js";
import { readAnchorStore, readOperations, readPointers, readRequirements } from "./store.js";

export const SYSTEM_WIDE = "System-wide";
export const RULES_DIR = join("docs", "rules");

/** The first line of every generated file, and how a write recognises its own files. */
export const GENERATED =
  "> Generated by codemap from the standard. Do not edit: edits are overwritten. Change a rule with a spec.";

const LEVEL_NAMES: Record<number, string> = { 1: "natural law", 2: "law", 3: "industry rule", 4: "business rule" };

/** A rule as the renderer needs it: the row, and where it applies, already worded. */
export interface ProjectedRule {
  rule: Requirement;
  appliesAt: string[];
  /** Each linked rule, worded (phase C). Optional so a rule with no links needs nothing. */
  restsOn?: string[];
  restedOnBy?: string[];
}

const slug = (area: string) =>
  area.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "area";

function renderRule({ rule: r, appliesAt, restsOn = [], restedOnBy = [] }: ProjectedRule): string {
  const lines = [`### ${r.title} — ${r.interim ? "provisional" : "ratified"}`, `Rule: ${r.statement}`];
  if (r.level) lines.push(`Level: ${r.level} ${LEVEL_NAMES[r.level]}`);
  if (r.authority) lines.push(`Authority: ${r.authority}`);
  lines.push(`Source: ${r.provenance}`);
  if (appliesAt.length) lines.push(`Applies at: ${appliesAt.join("; ")}`);
  if (r.lapsesWhen) lines.push(`Falsifier: ${r.lapsesWhen}`);
  if (restsOn.length) lines.push(`Rests on: ${restsOn.join("; ")}`);
  if (restedOnBy.length) lines.push(`Rested on by: ${restedOnBy.join("; ")}`);
  lines.push(`Id: ${r.id}`);
  return lines.join("\n");
}

/** Leveled rules, then the unleveled ones under their own counted heading. */
function renderGroup(rules: ProjectedRule[], scope: string): string[] {
  const leveled = rules.filter((p) => p.rule.level);
  const unleveled = rules.filter((p) => !p.rule.level);
  const out = leveled.map(renderRule);
  if (unleveled.length) {
    out.push(`## Unleveled${scope} (${unleveled.length})\n\nNo level recorded yet; they are in force all the same.`);
    out.push(...unleveled.map(renderRule));
  }
  return out;
}

/** An area's rules, with any sub-section (`Area/Sub`) as its own heading. */
function renderArea(area: string, rules: ProjectedRule[], label = ""): string[] {
  const subs = new Map<string, ProjectedRule[]>();
  for (const p of rules) {
    const sub = p.rule.section.slice(area.length + 1);
    subs.set(sub, [...(subs.get(sub) ?? []), p]);
  }
  const out: string[] = [];
  for (const [sub, members] of [...subs].sort(([a], [b]) => a.localeCompare(b))) {
    if (sub) out.push(`## ${sub}`);
    out.push(...renderGroup(members, sub ? ` — ${sub}` : label));
  }
  return out;
}

/**
 * Render the files. Pure, and deterministic: `rules` arrives in the order to print, and
 * nothing here reads the clock.
 */
export function renderRules(rules: ProjectedRule[]): Map<string, string> {
  const areas = new Map<string, ProjectedRule[]>();
  for (const p of rules) {
    const area = p.rule.section.split("/")[0]!;
    areas.set(area, [...(areas.get(area) ?? []), p]);
  }
  const files = new Map<string, string>();
  const named = [...areas.keys()].filter((a) => a !== SYSTEM_WIDE).sort((a, b) => a.localeCompare(b));
  const doc = (blocks: string[]) => blocks.join("\n\n") + "\n";

  const index = [
    GENERATED,
    "# Rules the system must obey",
    "The rules on the owner's solidity ladder: **1 natural law**, **2 law**, **3 industry rule**, "
    + "**4 business rule**. Levels 5-8 are design and below and are not stored here. Every rule is in "
    + "force. **ratified** means in force and not interim; **provisional** means in force and expected "
    + "to lose ground when its falsifier fires. (The standard's own `ratified` status covers both.) "
    + "A rule's **falsifier** is what would make it stop applying.",
    `## ${SYSTEM_WIDE} rules`,
    ...(areas.has(SYSTEM_WIDE) ? renderArea(SYSTEM_WIDE, areas.get(SYSTEM_WIDE)!, " system-wide rules") : ["None."]),
    "## Areas",
    named.length
      ? ["| Area | Rules | Doc |", "|---|---|---|",
        ...named.map((a) => `| ${a} | ${areas.get(a)!.length} | [${slug(a)}.md](${slug(a)}.md) |`)].join("\n")
      : "None.",
  ];
  files.set("INDEX.md", doc(index));
  for (const area of named) {
    files.set(`${slug(area)}.md`, doc([
      GENERATED,
      `# ${area}`,
      "Format and statuses: [INDEX.md](INDEX.md).",
      ...renderArea(area, areas.get(area)!),
    ]));
  }
  return files;
}

/** Where a pointer lands, worded for a reader: `file` `symbol` for an anchor here. */
function pointerText(p: Pointer, anchors: Map<string, Anchor>, universe?: string): string {
  const a = p.target.kind === "anchor" ? anchors.get(p.target.id) : undefined;
  const where = a ? `${a.file} ${a.symbolPath.join(".")}` : `${p.target.kind} ${p.target.id}`;
  return p.universe && p.universe !== universe ? `${p.universe}: ${where}` : where;
}

/** The in-force standard, in print order: by section, then the order the specs added them. */
export async function projectedRules(root: string): Promise<ProjectedRule[]> {
  const { requirements: every } = await readRequirements(root);
  const requirements = every.filter((r) => r.status === "ratified");
  const byId = new Map(every.map((r) => [r.id, r]));
  // A retired target stays linked and says so; the projection prints in-force rules only.
  const worded = (id: string) => {
    const t = byId.get(id);
    return t ? `"${t.title}" (${t.status === "retired" ? "retired" : t.interim ? "provisional" : "ratified"})` : id;
  };
  const ord = new Map<string, number>();
  for (const op of await readOperations(root, {}) as Operation[]) {
    if (op.kind === "add_requirement" && op.requirementId) ord.set(op.requirementId, op.ord);
  }
  let anchors = new Map<string, Anchor>();
  try { anchors = new Map((await readAnchorStore(root)).anchors.map((a) => [a.id, a])); } catch { /* not indexed: ids instead */ }
  const { universeKey } = await import("./sidecar-config.js");
  const universe = universeKey(root);
  const sorted = [...requirements].sort((a, b) =>
    a.section.localeCompare(b.section) || a.createdAt.localeCompare(b.createdAt)
    || (ord.get(a.id) ?? 0) - (ord.get(b.id) ?? 0) || a.id.localeCompare(b.id));
  const out: ProjectedRule[] = [];
  for (const rule of sorted) {
    const pointers = await readPointers(root, { requirementId: rule.id, state: "active" });
    out.push({
      rule, appliesAt: pointers.map((p) => pointerText(p, anchors, universe)).sort(),
      restsOn: (rule.restsOnRules ?? []).map(worded).sort(),
      restedOnBy: requirements.filter((x) => x.restsOnRules?.includes(rule.id)).map((x) => worded(x.id)).sort(),
    });
  }
  return out;
}

const git = (root: string, ...args: string[]) => spawnSync("git", args, { cwd: root, encoding: "utf8" });

/** Whether git tracks anything under `docs/rules/` here. */
export const rulesTracked = (root: string) => !!git(root, "ls-files", "--", RULES_DIR).stdout.trim();
/** Whether `docs/rules/` is ignored here, i.e. the repository has been cut over. */
// Asked of a file INSIDE it: git cannot tell an absent path is a directory, so a `docs/rules/`
// pattern does not match a bare `docs/rules` that does not exist yet.
export const rulesIgnored = (root: string) => git(root, "check-ignore", "-q", join(RULES_DIR, "INDEX.md")).status === 0;

export type RulesWhen = "command" | "sync" | "open";

/**
 * Write the projection.
 *
 * - `out` renders anywhere and skips the checks below: the caller chose the directory.
 * - Into `<root>/docs/rules/` it REFUSES while git tracks that path (the repository keeps
 *   its committed rules until its cutover), and an automatic write (`sync`, `open`) happens
 *   only where the path is ignored, since untracked files would dirty the tree and stop the
 *   next ladder run at its tree check. `open` also writes only when the directory is absent.
 */
export async function writeRulesProjection(
  root: string, opts: { out?: string; when?: RulesWhen } = {},
): Promise<{ ok: true; dir: string; written: string[]; removed: string[]; rules: number } | { skipped: string } | { error: string }> {
  const when = opts.when ?? "command";
  const dir = opts.out ? resolve(opts.out) : join(root, RULES_DIR);
  if (!opts.out) {
    // Before the tracked check, so a repository that has not been cut over (the normal case)
    // is skipped quietly by a sync rather than refused.
    if (when !== "command" && !rulesIgnored(root)) return { skipped: `${RULES_DIR}/ is not ignored here` };
    if (rulesTracked(root)) {
      return {
        error: `${RULES_DIR}/ is tracked by git here, so codemap will not write over it. `
          + "Generating it is for a repository that has been cut over: its rules ratified into the "
          + `standard and ${RULES_DIR}/ added to .gitignore. Use --out to render somewhere else.`,
      };
    }
    if (when === "open" && existsSync(dir)) return { skipped: `${RULES_DIR}/ already exists` };
  }
  const rules = await projectedRules(root);
  const files = renderRules(rules);
  mkdirSync(dir, { recursive: true });
  const written: string[] = [];
  for (const [name, text] of files) {
    const path = join(dir, name);
    if (existsSync(path) && readFileSync(path, "utf8") === text) continue;
    writeFileSync(path, text, "utf8");
    written.push(name);
  }
  // Only files this generated: anything else in the directory (a run record) is not ours.
  const removed: string[] = [];
  for (const name of readdirSync(dir)) {
    if (!name.endsWith(".md") || files.has(name)) continue;
    const path = join(dir, name);
    if (readFileSync(path, "utf8").startsWith(GENERATED)) { rmSync(path); removed.push(name); }
  }
  return { ok: true, dir, written, removed, rules: rules.length };
}

/** The `open` write for every universe a server starts on. A failure is reported, never thrown. */
export async function projectRulesOnOpen(roots: string[], report: (msg: string) => void): Promise<void> {
  for (const root of roots) {
    try {
      const r = await writeRulesProjection(root, { when: "open" });
      if ("error" in r) report(`rules projection for ${root}: ${r.error}`);
    } catch (e) { report(`rules projection for ${root}: ${(e as Error).message}`); }
  }
}
